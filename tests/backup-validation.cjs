const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const compiled = ts.transpileModule(fs.readFileSync('lib/db.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const loaded = new Module('backup-validation');
loaded._compile(compiled, 'backup-validation.js');
const { initialDatabase, defaultCompanyProfile, validateDatabaseBackup, importDatabaseJSON } = loaded.exports;
const {load}=require('../scripts/ts-loader.cjs');
const copy = () => load('lib/demo-seed.ts').buildDemo();
(async () => {
  assert.equal(validateDatabaseBackup(copy()).version, initialDatabase.version);
  const withProfile = { ...copy(), companyProfile: { ...defaultCompanyProfile, name: 'Test Foods' } };
  assert.equal(validateDatabaseBackup(withProfile).companyProfile.name, 'Test Foods');
  const withAdmin = { ...copy(), adminProfile: { name: 'Test Admin', email: 'admin@example.com', phone: '03000000000', title: 'Administrator' } };
  assert.deepEqual(validateDatabaseBackup(withAdmin).adminProfile, withAdmin.adminProfile);
  assert.throws(() => validateDatabaseBackup({ ...copy(), adminProfile: { name: 42 } }), /admin profile/);
  for (const invalid of [null, [], {}, { ...copy(), version: 999 }, { ...copy(), products: {} }, { ...copy(), companyProfile: { name: 42 } }]) assert.throws(() => validateDatabaseBackup(invalid));
  const duplicate = copy(); duplicate.products.push({ ...duplicate.products[0] });
  assert.throws(() => validateDatabaseBackup(duplicate), /duplicate/);
  const missing = copy(); delete missing.products[0].quantity;
  assert.throws(() => validateDatabaseBackup(missing), /Missing/);
  const malformed = copy(); malformed.invoices[0].items = [{ name: 'Bad', quantity: 'ten', unitPrice: 4 }];
  assert.throws(() => validateDatabaseBackup(malformed), /line items/);
  let writes = 0;
  global.window = { dispatchEvent() {} };
  global.localStorage = { setItem() { writes++; } };
  await importDatabaseJSON({ text: async () => JSON.stringify(withProfile) });
  assert.equal(writes, 0, 'Preview must not write to storage');
  await assert.rejects(importDatabaseJSON({ text: async () => '{invalid' }));
  console.log('Backup validation: valid data, profile round trip, malformed files, duplicate IDs, missing fields, line items and read-only preview passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
